#!/usr/bin/env python3
"""COR23C supplemental identity contract/consumer audit; native qualification remains mandatory."""
import argparse
import hashlib
import importlib.util
import json
import re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
REPORT='docs/corrections/FACTOR_IDENTITY_CONSUMER_REVIEW.json'
spec=importlib.util.spec_from_file_location('sql_bindings',Path(__file__).with_name('check-sql-output-bindings.py'))
bindings=importlib.util.module_from_spec(spec);spec.loader.exec_module(bindings)


def require(condition,message):
    if not condition:raise ValueError(message)


def method(source,name):
    # Bound one declaration by the next method. This is supplemental source checking only.
    start=re.search(r'\b'+re.escape(name)+r'\s*\([^;{]*\)\s*\{',source)
    require(start is not None,'Missing reader method: '+name)
    text=source[start.end():];depth=1
    for n,char in enumerate(text):
        if char=='{':depth+=1
        elif char=='}':depth-=1
        if depth==0:return text[:n]
    raise ValueError('Unbalanced reader method')


def validate_contract(root):
    sql=(root/bindings.CANONICAL).read_text();funcs=bindings.definitions(sql)
    require('two_factor_index bigint generated by default as identity (minvalue 0 start with 0 no cycle) not null' in sql,'Factor row identity must be noncycling bigint identity')
    require('priority smallint not null default 0' in sql,'Display priority must remain separate from row identity')
    for name in ['cor08_authorized_begin_authenticator_app_setup','cor16_begin_twofactor_setup']:
        body=funcs[name]
        require(not re.search(r'max\s*\([^)]*two_factor_index',body,re.I),'Fresh enrollment must not allocate from retained history')
        require('returning two_factor_authentications.two_factor_index into' in body,'Capture the database-owned identity')
        require(not re.search(r'insert into two_factor_authentications\([^)]*two_factor_index',body,re.I),'Fresh insert must let PostgreSQL allocate identity')
    for name,definition in funcs.items():
        require(not re.search(r'\b(?:two_factor_index|p_twoFactorIndex|p_index|target_index|idx) smallint\b',definition), 'Narrow SQL factor identity: '+name)
    for folder in ('Repos','Services','DataLayer'):
        for p in (root/folder).rglob('*.cs'):
            require(not re.search(r'\bshort\??\s+(?:TwoFactorIndex|twoFactorIndex)\b',p.read_text()),'Narrow C# factor identity: '+p.name)
    readers=[('Repos/AccountRepo.cs','ReadTwoFactorSetupCommandResultAsync',2),
        ('Repos/AuthenticatorAppEnrollmentRepo.cs','ReadBeginResultAsync',2),
        ('Repos/AuthenticatorAppEnrollmentRepo.cs','ReadPendingSetupAsync',2),
        ('Repos/AuthenticatorAppEnrollmentRepo.cs','ReadCompletionResultAsync',3),
        ('Repos/AuthenticatorAppEnrollmentRepo.cs','ReadVerifiedEnrollmentAsync',1)]
    for path,name,ordinal in readers:
        body=method((root/path).read_text(),name)
        require(f'GetInt64({ordinal})' in body and f'GetInt16({ordinal})' not in body,'Narrow reader: '+name)
    reset=(root/'Repos/PasswordResetTotpRepo.cs').read_text()
    require('dr.GetInt64(1)' in method(reset,'GetPasswordResetTotpEnrollmentAsync'),'Narrow reset enrollment reader')
    for path in ['Repos/AuthenticatorAppEnrollmentRepo.cs','Repos/PasswordResetTotpRepo.cs']:
        s=(root/path).read_text()
        require('"@twoFactorIndex", NpgsqlDbType.Bigint' in s,'Narrow replay parameter: '+path)
    replay=funcs['mark_totp_step_used']
    require('t.totp_enrollment_id = p_enrollmentId' in replay and 't.verified = true and t.revoked_at is null' in replay,'Replay must bind the live enrollment UUID')
    require('enrollment = context.EnrollmentId.ToString("N")' in (root/'Services/TotpSecretProtectionService.cs').read_text(),'Secret associated data must retain UUID binding')
    bindings.validate_critical(sql)
    return funcs


def audit(root):
    funcs=validate_contract(root);rows=[]
    for path in sorted(root.rglob('*')):
        if not path.is_file() or path.suffix not in ('.cs','.sql') or set(path.relative_to(root).parts)&{'.git','bin','obj','.artifacts','.correction-results','TestResults','__pycache__'}:continue
        source=path.read_text();matches=[dict(line=n,text=l.strip()) for n,l in enumerate(source.splitlines(),1) if re.search(r'\b(?:TwoFactorIndex|twoFactorIndex|two_factor_index|p_twoFactorIndex)\b',l)]
        if matches:rows.append(dict(path=path.relative_to(root).as_posix(),sha256=hashlib.sha256(path.read_bytes()).hexdigest(),references=matches))
    return dict(schema_version=1,basis='Lexical current consumer inventory and focused type/allocator/UUID checks; not compilation or execution',qualification='NotRun',
                factor_row_identity='Database-owned noncycling bigint; retained/deleted rows never determine allocation',enrollment_identity='Existing immutable request/TOTP enrollment UUID; pending replacement changes enrollment UUID, not row slot',
                display_order='Existing required/priority fields; row identity remains a deterministic tie-breaker only',
                widened_function_contracts=sorted(n for n,f in funcs.items() if re.search(r'\b(?:two_factor_index|p_twoFactorIndex|p_index) bigint\b',f.split('as $$',1)[0])),files=rows)


def validate(root):
    expected=audit(root)
    require(json.loads((root/REPORT).read_text())==expected,'Identity consumer inventory is stale; refresh intentional edits')
    return expected


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--root',type=Path,default=ROOT);p.add_argument('--refresh',action='store_true');args=p.parse_args()
    try:
        if args.refresh:(args.root/REPORT).write_text(json.dumps(audit(args.root),indent=2)+'\n')
        report=validate(args.root);print(f"Identity source contracts agree: {len(report['widened_function_contracts'])} functions, {len(report['files'])} consumer files. Native qualification pending.");return 0
    except (ValueError,OSError,KeyError) as e:print(str(e));return 1


if __name__=='__main__':raise SystemExit(main())
