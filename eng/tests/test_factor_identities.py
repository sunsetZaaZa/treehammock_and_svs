"""Supplemental contract mutations, never substitutes for native boundary/concurrency tests."""
import importlib.util
import shutil
import tempfile
import unittest
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
spec=importlib.util.spec_from_file_location('factor_ids',ROOT/'eng/check-factor-identities.py')
ids=importlib.util.module_from_spec(spec);spec.loader.exec_module(ids)

class FactorIdentityTests(unittest.TestCase):
    def setUp(self):
        self.temp=tempfile.TemporaryDirectory();self.root=Path(self.temp.name)/'source'
        shutil.copytree(ROOT,self.root,ignore=shutil.ignore_patterns('.git','bin','obj','.artifacts','.correction-results','TestResults','__pycache__'))
    def tearDown(self):self.temp.cleanup()
    def replace(self,path,old,new):
        p=self.root/path;s=p.read_text();self.assertIn(old,s);p.write_text(s.replace(old,new,1))
    def test_current_consumer_audit_preserves_uuid_binding_and_native_pending(self):
        report=ids.validate(self.root)
        self.assertEqual(len(report['widened_function_contracts']),11);self.assertEqual(report['qualification'],'NotRun')
    def test_smallint_identity_and_cycling_allocator_are_rejected(self):
        for bad in ('smallint generated by default as identity (minvalue 0 start with 0 no cycle)', 'bigint generated by default as identity (minvalue 0 start with 0 cycle)'):
            p=self.root/ids.bindings.CANONICAL;original=p.read_text()
            p.write_text(original.replace('bigint generated by default as identity (minvalue 0 start with 0 no cycle)',bad,1))
            with self.subTest(bad=bad),self.assertRaises(ValueError):ids.validate_contract(self.root)
            p.write_text(original)
    def test_history_max_allocation_is_rejected(self):
        self.replace(ids.bindings.CANONICAL,'idx:=null;version:=1;','select max(t.two_factor_index)+1 into idx from two_factor_authentications t;version:=1;')
        with self.assertRaises(ValueError):ids.validate_contract(self.root)
    def test_explicit_insert_identity_is_rejected(self):
        self.replace(ids.bindings.CANONICAL,'insert into two_factor_authentications(account_id, token','insert into two_factor_authentications(two_factor_index,account_id, token')
        with self.assertRaises(ValueError):ids.validate_contract(self.root)
    def test_each_actual_reader_rejects_narrowing(self):
        for path,name,ordinal in [('Repos/AccountRepo.cs','ReadTwoFactorSetupCommandResultAsync',2),('Repos/AuthenticatorAppEnrollmentRepo.cs','ReadBeginResultAsync',2),('Repos/AuthenticatorAppEnrollmentRepo.cs','ReadPendingSetupAsync',2),('Repos/AuthenticatorAppEnrollmentRepo.cs','ReadCompletionResultAsync',3),('Repos/AuthenticatorAppEnrollmentRepo.cs','ReadVerifiedEnrollmentAsync',1),('Repos/PasswordResetTotpRepo.cs','GetPasswordResetTotpEnrollmentAsync',1)]:
            p=self.root/path;original=p.read_text();body=ids.method(original,name)
            p.write_text(original.replace(body,body.replace(f'GetInt64({ordinal})',f'GetInt16({ordinal})',1),1))
            with self.subTest(name=name),self.assertRaises(ValueError):ids.validate_contract(self.root)
            p.write_text(original)
    def test_replay_parameter_narrowing_is_rejected(self):
        self.replace('Repos/PasswordResetTotpRepo.cs','"@twoFactorIndex", NpgsqlDbType.Bigint','"@twoFactorIndex", NpgsqlDbType.Smallint')
        with self.assertRaises(ValueError):ids.validate_contract(self.root)
    def test_cross_enrollment_replay_binding_cannot_be_removed(self):
        p=self.root/ids.bindings.CANONICAL;s=p.read_text();definition=ids.bindings.definitions(s)['mark_totp_step_used']
        p.write_text(s.replace(definition,definition.replace('t.totp_enrollment_id = p_enrollmentId','true'),1))
        with self.assertRaises(ValueError):ids.validate_contract(self.root)
    def test_secret_binding_must_retain_enrollment_uuid(self):
        self.replace('Services/TotpSecretProtectionService.cs','enrollment = context.EnrollmentId.ToString("N")','enrollment = context.AccountId.ToString("N")')
        with self.assertRaises(ValueError):ids.validate_contract(self.root)
    def test_new_unreviewed_consumer_makes_inventory_stale(self):
        (self.root/'Repos/Unreviewed.cs').write_text('record Unreviewed(long TwoFactorIndex);')
        with self.assertRaises(ValueError):ids.validate(self.root)

if __name__=='__main__':unittest.main()
